// Caddy supervisor — admin-set custom domain + free Let's Encrypt SSL.
import { spawn } from 'child_process';
import fs from 'fs';
import path from 'path';
import { q, q1 } from './db.js';

const CADDY_DIR = process.env.CADDY_DIR || '/data/caddy';
const CADDY_FILE = path.join(CADDY_DIR, 'Caddyfile');
fs.mkdirSync(path.join(CADDY_DIR, 'storage'), { recursive: true });

let proc = null;

export function isRunning() { return !!proc && proc.exitCode === null; }
export function getCaddyDir() { return CADDY_DIR; }

function buildCaddyfile(domain, acmeEmail, upstreamPort) {
  const email = acmeEmail && /@/.test(acmeEmail) ? acmeEmail : `admin@${domain}`;
  const storage = path.join(CADDY_DIR, 'storage').replace(/\\/g, '/');
  const accessLog = path.join(CADDY_DIR, 'access.log').replace(/\\/g, '/');
  return `# Generated by Elyon Explorer admin — do not hand-edit.
{
    email ${email}
    storage file_system {
        root ${storage}
    }
}

${domain} {
    reverse_proxy 127.0.0.1:${upstreamPort}
    encode gzip
    log {
        output file ${accessLog}
        format console
    }
}
`;
}

export function stopCaddy() {
  return new Promise(resolve => {
    if (!proc) return resolve();
    const p = proc;
    const t = setTimeout(() => { try { p.kill('SIGKILL'); } catch {} resolve(); }, 8000);
    p.once('exit', () => { clearTimeout(t); resolve(); });
    try { p.kill('SIGTERM'); } catch {}
    proc = null;
  });
}

export async function applyDomain(domain, acmeEmail, upstreamPort) {
  await stopCaddy();
  if (!domain) return;
  if (!/^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$/i.test(domain)) {
    console.warn('[caddy] invalid domain', domain); return;
  }
  try {
    fs.writeFileSync(CADDY_FILE, buildCaddyfile(domain, acmeEmail, upstreamPort));
  } catch (e) {
    console.warn('[caddy] cannot write Caddyfile:', e.message); return;
  }
  try {
    proc = spawn('caddy', ['run', '--config', CADDY_FILE, '--adapter', 'caddyfile'], {
      stdio: 'pipe',
      env: { ...process.env, HOME: CADDY_DIR },
    });
    proc.stdout.on('data', d => process.stdout.write('[caddy] ' + d));
    proc.stderr.on('data', d => process.stderr.write('[caddy] ' + d));
    proc.on('exit', code => { console.log('[caddy] exit', code); proc = null; });
    console.log('[caddy] started for', domain);
  } catch (e) {
    console.warn('[caddy] spawn failed (is caddy on PATH?):', e.message);
    proc = null;
  }
}

export async function autoStart(upstreamPort) {
  try {
    const r = await q1('SELECT domain, acme_email FROM domain_config WHERE id = 1');
    if (r?.domain) {
      console.log('[caddy] auto-starting for stored domain', r.domain);
      await applyDomain(r.domain, r.acme_email, upstreamPort);
    }
  } catch (e) { console.warn('[caddy] auto-start skipped:', e.message); }
}

export async function readDomainConfig() {
  return await q1('SELECT domain, acme_email, updated_at FROM domain_config WHERE id = 1');
}
export async function saveDomainConfig(domain, acmeEmail) {
  await q('UPDATE domain_config SET domain = $1, acme_email = $2, updated_at = NOW() WHERE id = 1',
    [domain || null, acmeEmail || null]);
}
